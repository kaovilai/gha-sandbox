// Zero-dep ACP agent (NDJSON JSON-RPC over stdio) that plays provider-neutral scenarios.
// Targets the T3 Code `grok` / `acpRegistry` driver flavors. Frame shapes copied from upstream
// apps/server/src/orchestration-v2/testkit/fixtures/*/grok_transcript.ndjson.
import { createInterface } from "node:readline";
import { randomUUID } from "node:crypto";
import { existsSync, statSync } from "node:fs";
import { ScenarioError, runSteps } from "../lib/ir.mjs";
import { makeLog } from "../lib/log.mjs";
import { abortError, makePace } from "../lib/pace.mjs";
import { isTextGen, parseTag, promptText, stripTags, userRequest } from "../lib/select.mjs";
import { dequeue } from "../lib/queue.mjs";
import { loadScenarios } from "../scenarios/index.mjs";

const MODELS = [
  { modelId: "grok-build", name: "Mock Build" },
  { modelId: "grok-mock-fast", name: "Mock Fast" },
];

const COMMANDS = [
  { name: "compact", description: "Compress conversation history to save context window", input: { hint: "optional context about what to preserve" } },
  { name: "mock", description: "Mock agent: pick a scenario with [mock:<id>] in your message, or queue one with mockctl next", input: { hint: "<scenario id>" } },
];

export function serveAcp({ input = process.stdin, output = process.stdout, env = process.env } = {}) {
  const log = makeLog(env.MOCK_LOG, { agent: "acp" });
  const pace = makePace(env);
  const sessions = new Map();
  const pendingOut = new Map(); // our requests to the client, by id
  let clientName = "";
  let nextOutId = 9000;
  let nextTool = 0;

  const write = (obj) => {
    log("out", { frame: obj });
    output.write(`${JSON.stringify(obj)}\n`);
  };
  const notify = (method, params) => write({ jsonrpc: "2.0", method, params });
  const update = (sessionId, u) => notify("session/update", { sessionId, update: u });
  const xUpdate = (sessionId, u) => notify("_x.ai/session_notification", { sessionId, update: u });
  const reply = (id, result) => write({ jsonrpc: "2.0", id, result });
  const fail = (id, code, message, data) => write({ jsonrpc: "2.0", id, error: { code, message, ...(data ? { data } : {}) } });
  const callClient = (method, params, signal) =>
    new Promise((resolve, reject) => {
      const id = nextOutId++;
      pendingOut.set(id, { resolve, reject });
      signal?.addEventListener(
        "abort",
        () => {
          if (pendingOut.delete(id)) reject(abortError());
        },
        { once: true },
      );
      write({ jsonrpc: "2.0", id, method, params });
    });

  function modelState(current) {
    return {
      currentModelId: current,
      availableModels: MODELS.map((m) => ({ ...m, _meta: { totalContextTokens: 200000, agentType: "mock" } })),
    };
  }
  const configOptions = (current) => [
    {
      id: "model",
      name: "Model",
      category: "model",
      type: "select",
      currentValue: current,
      options: MODELS.map((m) => ({ value: m.modelId, name: m.name })),
    },
  ];

  function newSession(cwd, id = randomUUID()) {
    const s = { id, cwd: cwd && existsSync(cwd) && statSync(cwd).isDirectory() ? cwd : process.cwd(), turn: 0, history: [], model: MODELS[0].modelId, abort: null };
    sessions.set(id, s);
    return s;
  }

  // ---- text generation (titles / commit / PR / branch): bypass scenarios, answer valid JSON ------
  async function textGenReply(text) {
    const scenarios = await loadScenarios();
    const retLine = (text.match(/Return[^\n]*/g) ?? []).find((l) => /JSON|key/i.test(l)) ?? "";
    const wants = (k) => new RegExp(`\\b${k}\\b`).test(retLine);
    const um = text.match(/(?:User message|Thread contents):\n([\s\S]*)/);
    const basis = um ? um[1] : "";
    const tag = parseTag(basis);
    const cleaned = stripTags(basis).replace(/\s+/g, " ").trim();
    const title = (tag && scenarios.get(tag.id)?.title) || cleaned.split(" ").slice(0, 7).join(" ") || "Mock thread";
    const out = {};
    if (wants("title")) out.title = title;
    if (wants("needsRefinement")) out.needsRefinement = false;
    if (wants("subject")) out.subject = "Update files via mock agent";
    if (wants("body")) out.body = "Generated by the mockkit text-generation stub.";
    if (wants("branch")) out.branch = `mock/${title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 30) || "change"}`;
    if (wants("stops")) out.stops = [];
    if (Object.keys(out).length === 0) out.title = title;
    return JSON.stringify(out);
  }

  // ---- IR sink -> ACP frames ------------------------------------------------------------------
  function makeSink(s, signal) {
    const content = ({ text, diff }) => [
      ...(diff ? [{ type: "diff", path: diff.path, oldText: diff.oldText, newText: diff.newText }] : []),
      ...(text !== undefined ? [{ type: "content", content: { type: "text", text } }] : []),
    ];
    return {
      message: (text) => update(s.id, { sessionUpdate: "agent_message_chunk", content: { type: "text", text } }),
      thought: (text) => update(s.id, { sessionUpdate: "agent_thought_chunk", content: { type: "text", text } }),
      toolStart: (t) =>
        update(s.id, {
          sessionUpdate: "tool_call",
          toolCallId: t.id,
          title: t.title,
          kind: t.kind,
          status: t.status ?? "in_progress",
          ...(t.input !== undefined ? { rawInput: t.input } : {}),
          ...(t.locations ? { locations: t.locations } : {}),
          ...(t.diff ? { content: content({ diff: t.diff }) } : {}),
        }),
      toolUpdate: (t) =>
        update(s.id, {
          sessionUpdate: "tool_call_update",
          toolCallId: t.id,
          status: t.status,
          ...(t.text !== undefined || t.diff ? { content: content(t) } : {}),
          ...(t.output !== undefined ? { rawOutput: t.output } : {}),
        }),
      plan: (entries) => update(s.id, { sessionUpdate: "plan", entries }),
      permission: async (p) => {
        const res = await callClient(
          "session/request_permission",
          {
            sessionId: s.id,
            toolCall: {
              toolCallId: p.id,
              kind: p.kind,
              title: p.title,
              ...(p.input !== undefined ? { rawInput: p.input } : {}),
              ...(p.diff ? { content: content({ diff: p.diff }), locations: [{ path: p.diff.path }] } : {}),
            },
            options: p.options ?? [
              ...(p.kind === "edit" ? [{ optionId: "allow-edits-session", name: "Yes, allow all edits during this session", kind: "allow_always" }] : []),
              { optionId: "allow-once", name: "Yes", kind: "allow_once" },
              { optionId: "reject-once", name: "No, and tell the agent what to do differently", kind: "reject_once" },
            ],
          },
          signal,
        );
        const o = res?.outcome;
        if (o?.outcome === "cancelled") return "cancel";
        return /reject/i.test(o?.optionId ?? "") ? "reject" : "allow";
      },
      ask: async ({ questions }) => {
        const res = await callClient(
          "_x.ai/ask_user_question",
          { method: "x.ai/ask_user_question", params: { sessionId: s.id, toolCallId: `mock-ask-${++nextTool}`, questions: questions.map((q) => ({ multiSelect: null, ...q })), mode: "default" } },
          signal,
        );
        return res;
      },
    };
  }

  async function handlePrompt(id, params) {
    const s = sessions.get(params.sessionId) ?? newSession(undefined, params.sessionId);
    const raw = promptText(params.prompt);
    if (isTextGen({ clientName, text: raw })) {
      const json = await textGenReply(raw);
      update(s.id, { sessionUpdate: "agent_message_chunk", content: { type: "text", text: json } });
      log("textgen", { reply: json });
      return reply(id, { stopReason: "end_turn" });
    }
    const req = userRequest(raw);
    // Selection order: explicit "[mock:id]" tag in the prompt, else the hidden per-cwd queue (mockctl next), else default.
    const tag =
      parseTag(req) ??
      (() => {
        const q = dequeue(s.cwd, { ...process.env, ...env });
        return q ? { id: q.id, args: q.args, text: req, queued: true } : null;
      })();
    const scenarios = await loadScenarios();
    const scenario = (tag && scenarios.get(tag.id)) || scenarios.get(env.MOCK_DEFAULT_SCENARIO || "echo");
    s.turn += 1;
    const ac = new AbortController();
    s.abort = ac;
    const ctx = {
      cwd: s.cwd,
      env: { ...process.env, ...env },
      turn: s.turn,
      args: tag?.args ?? {},
      text: tag?.text ?? req,
      history: s.history,
      sessionId: s.id,
      signal: ac.signal,
      pace,
      log,
      answers: {},
      nextToolId: () => `mock-call-${++nextTool}`,
    };
    log("prompt", { scenario: scenario.id, turn: s.turn, tag: tag?.id ?? null, queued: Boolean(tag?.queued), text: ctx.text.slice(0, 200) });
    const sink = makeSink(s, ac.signal);
    try {
      await runSteps(scenario.steps(ctx), sink, ctx);
      s.history.push(ctx.text);
      reply(id, { stopReason: "end_turn", _meta: { sessionId: s.id, modelId: s.model } });
    } catch (e) {
      s.history.push(ctx.text);
      if (e?.name === "AbortError" || ac.signal.aborted) {
        reply(id, { stopReason: "cancelled" });
      } else if (e instanceof ScenarioError) {
        xUpdate(s.id, { sessionUpdate: "retry_state", type: "failed", error_type: "api", message: e.message });
        xUpdate(s.id, { sessionUpdate: "turn_completed", prompt_id: params._meta?.promptId ?? "mock", stop_reason: "error", agent_result: e.message });
        fail(id, e.code, "Internal error", { message: e.message, http_status: 400 });
      } else {
        log("crash", { error: String(e?.stack ?? e) });
        fail(id, -32603, "Internal error", { message: String(e?.message ?? e) });
      }
    } finally {
      s.abort = null;
    }
  }

  async function handleRequest(msg) {
    const { id, method, params = {} } = msg;
    switch (method) {
      case "initialize":
        clientName = params.clientInfo?.name ?? "";
        return reply(id, {
          protocolVersion: 1,
          agentCapabilities: {
            loadSession: true,
            promptCapabilities: { image: false, audio: false, embeddedContext: true },
            mcpCapabilities: { http: true, sse: true },
            sessionCapabilities: { list: {}, resume: {}, close: {} },
            auth: {},
          },
          authMethods: [{ id: "cached_token", name: "cached_token", description: "Mock token (no real auth)" }],
          _meta: {
            agentVersion: "mock",
            modelState: modelState(MODELS[0].modelId),
            availableCommands: COMMANDS,
          },
        });
      case "authenticate":
        return reply(id, {});
      case "session/new": {
        const s = newSession(params.cwd);
        reply(id, {
          sessionId: s.id,
          models: modelState(s.model),
          configOptions: configOptions(s.model),
          _meta: { currentWorkingDirectory: s.cwd, isGitRepo: true },
        });
        update(s.id, { sessionUpdate: "available_commands_update", availableCommands: COMMANDS });
        return;
      }
      case "session/load":
      case "session/resume": {
        const s = sessions.get(params.sessionId) ?? newSession(params.cwd, params.sessionId);
        return reply(id, { models: modelState(s.model), configOptions: configOptions(s.model) });
      }
      case "session/set_model": {
        const s = sessions.get(params.sessionId);
        if (!MODELS.some((m) => m.modelId === params.modelId)) return fail(id, -32602, "Unknown mock model");
        if (s) s.model = params.modelId;
        return reply(id, {});
      }
      case "session/set_config_option": {
        const s = sessions.get(params.sessionId);
        if (s && params.configId === "model" && typeof params.value === "string") s.model = params.value;
        return reply(id, { configOptions: configOptions(s?.model ?? MODELS[0].modelId) });
      }
      case "session/set_mode":
        return reply(id, {});
      case "session/list":
        return reply(id, { sessions: [] });
      case "session/close":
        sessions.get(params.sessionId)?.abort?.abort();
        sessions.delete(params.sessionId);
        return reply(id, {});
      case "session/prompt":
        return handlePrompt(id, params);
      default:
        return fail(id, -32601, "Method not found");
    }
  }

  const rl = createInterface({ input });
  rl.on("line", (line) => {
    if (!line.trim()) return;
    log("in", { raw: line.length > 4000 ? `${line.slice(0, 4000)}...` : line });
    let msg;
    try {
      msg = JSON.parse(line);
    } catch {
      return;
    }
    if (msg.method && msg.id !== undefined) {
      handleRequest(msg).catch((e) => {
        log("crash", { error: String(e?.stack ?? e) });
        fail(msg.id, -32603, "Internal error", { message: String(e?.message ?? e) });
      });
    } else if (msg.method) {
      if (msg.method === "session/cancel") sessions.get(msg.params?.sessionId)?.abort?.abort();
    } else if (msg.id !== undefined) {
      const p = pendingOut.get(msg.id);
      if (p) {
        pendingOut.delete(msg.id);
        if (msg.error) p.reject(new Error(msg.error.message ?? "client error"));
        else p.resolve(msg.result);
      }
    }
  });
  return new Promise((resolve) =>
    rl.on("close", () => {
      for (const s of sessions.values()) s.abort?.abort();
      resolve();
    }),
  );
}
