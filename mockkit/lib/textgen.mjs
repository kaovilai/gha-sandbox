// Text-generation (thread titles, commit / PR / branch text) answered without running a scenario.
// Shared by the ACP and Codex adapters. Returns a JSON string.
//   textGenJson(promptText, scenarios, { keys })  keys = explicit output keys (Codex: from --output-schema "properties")
import { parseTag, stripTags } from "./select.mjs";

export function textGenJson(text, scenarios, { keys } = {}) {
  const retLine = (text.match(/Return[^\n]*/g) ?? []).find((l) => /JSON|key/i.test(l)) ?? "";
  const wants = (k) => (keys ? keys.includes(k) : new RegExp(`\\b${k}\\b`).test(retLine));
  const um = text.match(/(?:User message|Thread contents):\n([\s\S]*)/);
  const basis = um ? um[1] : "";
  const tag = parseTag(basis);
  const cleaned = stripTags(basis).replace(/\s+/g, " ").trim();
  const title = (tag && scenarios.get(tag.id)?.title) || cleaned.split(" ").slice(0, 7).join(" ") || "Mock thread";
  const out = {};
  if (wants("title")) out.title = title;
  if (wants("needsRefinement")) out.needsRefinement = false;
  if (wants("subject")) out.subject = "Update files via mock agent";
  if (wants("body")) out.body = "Generated by the mockkit text-generation stub.";
  if (wants("branch")) out.branch = `mock/${title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 30) || "change"}`;
  if (wants("stops")) out.stops = [];
  if (Object.keys(out).length === 0) out.title = title;
  return JSON.stringify(out);
}
